    async def open_drawer(
        self,
        user_id: uuid.UUID,
        opening_amount: Decimal,
        cashier_id: uuid.UUID | None = None,
    ) -> CashDrawer:
        """Open a new cash drawer. Raises if one is already open."""
        existing = await self.get_open_drawer()
        if existing:
            raise InvalidOperation("A cash drawer is already open")
        drawer = CashDrawer(
            user_id=user_id,
            cashier_id=cashier_id,
            opened_at=datetime.now(timezone.utc),
            opening_amount=float(opening_amount),
            is_open=True,
        )
        self.db.add(drawer)
        await self.db.flush()
        await self.db.refresh(drawer)
        return drawer

    async def close_drawer(
        self,
        user_id: uuid.UUID,
        closing_amount: Decimal,
        cashier_id: uuid.UUID | None = None,
    ) -> CashDrawer:
        """Close the currently open drawer.

        Computes *expected_amount* as opening_amount + sum of cash payments
        made while the drawer was open. If a cashier_id is supplied, it
        replaces the one set at opening (e.g. shift handover).
        """
        drawer = await self.get_open_drawer()
        if not drawer:
            raise ResourceNotFound("CashDrawer")
        if cashier_id is not None:
            drawer.cashier_id = cashier_id

        # Sum cash payments during the drawer period
        cash_sum_result = await self.db.execute(
            select(func.coalesce(func.sum(Payment.amount), 0))
            .join(Transaction, Payment.transaction_id == Transaction.id)
            .where(
                Payment.method == PaymentMethod.cash,
                Transaction.created_at >= drawer.opened_at,
            )
        )
        cash_total = Decimal(str(cash_sum_result.scalar_one()))

        drawer.closing_amount = float(closing_amount)
        drawer.expected_amount = float(
            Decimal(str(drawer.opening_amount)) + cash_total
        )
        drawer.closed_at = datetime.now(timezone.utc)
        drawer.is_open = False

        await self.db.flush()
        await self.db.refresh(drawer)
        return drawer

    async def get_open_drawer(self) -> CashDrawer | None:
        """Return the currently open cash drawer, or None."""
        result = await self.db.execute(
            select(CashDrawer).where(CashDrawer.is_open.is_(True)).limit(1)
        )
        return result.scalar_one_or_none()

    async def finalize_sale(
        self,
        transaction: Transaction,
        *,
        coupon_code: str | None,
        user_id: uuid.UUID,
    ) -> None:
        """Post-sign finalization: coupon redemption + loyalty + analytics events.

        Called from the router after FiscalService.sign_transaction(). Failures in
        any step are logged and swallowed — they never roll back the signed sale.
        """
        import logging as _logging
        _log = _logging.getLogger("vintiz")

        # Coupon redemption
        if coupon_code:
            from app.services.coupon import CouponError, redeem_coupon, validate_coupon
            try:
                preview = await validate_coupon(
                    self.db,
                    code=coupon_code,
                    cart_total=float(transaction.total_ttc),
                    client_id=transaction.client_id,
                )
                await redeem_coupon(self.db, preview.coupon_id, transaction.id)
            except CouponError as exc:
                _log.warning(
                    "Coupon redemption failed for tx=%s code=%s reason=%s",
                    transaction.id, coupon_code, exc,
                )

        # Loyalty: 1 € = 1 pt; every 100 pts crossed → 8 € coupon (60d, auto)
        if transaction.client_id is not None:
            try:
                await self._credit_loyalty_and_emit_milestones(transaction)
            except Exception as exc:  # noqa: BLE001
                _log.warning(
                    "Loyalty milestone hook failed for tx=%s: %s",
                    transaction.id, exc,
                )

        # Emit analytics events (P1-003)
        from app.models.events import EventSource, EventType
        from app.services.events import EventService
        events = EventService(self.db)
        if transaction.client_id is not None:
            await events.emit(
                EventType.customer_visited,
                source=EventSource.pos,
                customer_id=transaction.client_id,
                transaction_id=transaction.id,
                user_id=user_id,
            )
        for item in (transaction.items or []):
            if item.product_id is None:
                continue
            await events.emit(
                EventType.product_sold,
                source=EventSource.pos,
                customer_id=transaction.client_id,
                product_id=item.product_id,
                transaction_id=transaction.id,
                user_id=user_id,
                meta={
                    "quantity": int(item.quantity),
                    "unit_price": float(item.unit_price),
                    "discount_percent": float(item.discount_percent or 0),
                },
            )

    # ------------------------------------------------------------------
    # Loyalty (1 € = 1 pt, 100 pts = 8 € auto)
    # ------------------------------------------------------------------

    async def _credit_loyalty_and_emit_milestones(
        self, transaction: Transaction
    ) -> None:
        """Credit points + emit milestone coupons.

        Only invoked when the sale has a client. Loads/creates the
        ``LoyaltyAccount`` lazily so unenrolled clients still earn points
        from the moment they share their email.
        """
        from app.models.client import (
            LoyaltyAccount,
            LoyaltyTransaction,
            LoyaltyTxType,
        )
        from app.models.coupon import Coupon, CouponDiscountType, CouponSource
        from app.services.coupon import _draw_unique_code  # collision-safe helper
        from app.services.offers_engine import (
            LOYALTY_VOUCHER_VALID_DAYS,
            LOYALTY_VOUCHER_VALUE,
            milestones_crossed,
            points_to_credit,
        )

        amount = float(transaction.total_ttc or 0)
        points = points_to_credit(amount)
        if points <= 0:
            return

        result = await self.db.execute(
            select(LoyaltyAccount).where(
                LoyaltyAccount.client_id == transaction.client_id
            )
        )
        account = result.scalar_one_or_none()
        if account is None:
            from app.services.membership_id import generate_membership_number

            membership = await generate_membership_number(self.db)
            account = LoyaltyAccount(
                client_id=transaction.client_id,
                points=0,
                membership_number=membership,
            )
            self.db.add(account)
            await self.db.flush()

        # Idempotency guard: a replay (e.g. router crash between flush and
        # commit on the first attempt) must NOT credit the same sale twice.
        # The earn ledger row is keyed by the unique transaction_number.
        sale_marker = f"Sale #{transaction.transaction_number}"
        already = await self.db.execute(
            select(LoyaltyTransaction.id).where(
                LoyaltyTransaction.account_id == account.id,
                LoyaltyTransaction.tx_type == LoyaltyTxType.earn,
                LoyaltyTransaction.description == sale_marker,
            ).limit(1)
        )
        if already.scalar_one_or_none() is not None:
            return

        before = int(account.points or 0)
        account.points = before + points
        self.db.add(LoyaltyTransaction(
            account_id=account.id,
            tx_type=LoyaltyTxType.earn,
            points=points,
            description=sale_marker,
        ))

        crossed = milestones_crossed(before, account.points)
        if crossed <= 0:
            return

        now = datetime.now(timezone.utc)
        valid_until = now + timedelta(days=LOYALTY_VOUCHER_VALID_DAYS)
        for _ in range(crossed):
            code = await _draw_unique_code(self.db, "LOYAL")
            self.db.add(Coupon(
                code=code,
                client_id=transaction.client_id,
                discount_type=CouponDiscountType.amount,
                discount_value=LOYALTY_VOUCHER_VALUE,
                source=CouponSource.loyalty_milestone,
                valid_from=now,
                valid_until=valid_until,
                is_active=True,
                notes=f"Palier {LOYALTY_VOUCHER_VALUE:.0f} € — atteint sur tx #{transaction.transaction_number}",
            ))
