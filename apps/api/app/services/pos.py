    # Loyalty (1 € = 1 pt, 100 pts = chèque cadeau 5 € auto)
    # ------------------------------------------------------------------

    async def _credit_loyalty_and_emit_milestones(
        self, transaction: Transaction
    ) -> None:
        """Credit points + emit milestone coupons.

        Only invoked when the sale has a client. Loads/creates the
        ``LoyaltyAccount`` lazily so unenrolled clients still earn points
        from the moment they share their email.
        """
        from app.models.client import (
            LoyaltyAccount,
            LoyaltyTransaction,
            LoyaltyTxType,
        )
        from app.models.coupon import Coupon, CouponDiscountType, CouponSource
        from app.services.coupon import _draw_unique_code  # collision-safe helper
        from app.services.loyalty_config import get_earning_config
        from app.services.offers_engine import (
            milestones_crossed,
            points_to_credit,
        )

        cfg = await get_earning_config(self.db)
        # Les articles en promotion / opération (Solde, markdown) ne cotisent
        # PAS de points de fidélité : on ne crédite que sur les lignes non
        # promotionnelles. Repli sur total_ttc si la vente n'a pas d'items
        # chargés (compat anciens appels / seeds).
        items = list(transaction.items or [])
        if items:
            eligible_amount = sum(
                float(item.line_total or 0)
                for item in items
                if not getattr(item, "promotional", False)
            )
        else:
            eligible_amount = float(transaction.total_ttc or 0)
        points = points_to_credit(eligible_amount, cfg.euro_per_point)
        if points <= 0:
            return

        result = await self.db.execute(
            select(LoyaltyAccount).where(
                LoyaltyAccount.client_id == transaction.client_id
            )
        )
        account = result.scalar_one_or_none()
        if account is None:
            from app.services.membership_id import generate_membership_number

            membership = await generate_membership_number(self.db)
            account = LoyaltyAccount(
                client_id=transaction.client_id,
                points=0,
                membership_number=membership,
            )
            self.db.add(account)
            await self.db.flush()

        # Idempotency guard: a replay (e.g. router crash between flush and
        # commit on the first attempt) must NOT credit the same sale twice.
        # The earn ledger row is keyed by the unique transaction_number.
        sale_marker = f"Sale #{transaction.transaction_number}"
        already = await self.db.execute(
            select(LoyaltyTransaction.id).where(
                LoyaltyTransaction.account_id == account.id,
                LoyaltyTransaction.tx_type == LoyaltyTxType.earn,
                LoyaltyTransaction.description == sale_marker,
            ).limit(1)
        )
        if already.scalar_one_or_none() is not None:
            return

        before = int(account.points or 0)
        account.points = before + points
        self.db.add(LoyaltyTransaction(
            account_id=account.id,
            tx_type=LoyaltyTxType.earn,
            points=points,
            description=sale_marker,
        ))

        crossed = milestones_crossed(before, account.points, cfg.voucher_threshold)
        if crossed <= 0:
            return

        now = datetime.now(timezone.utc)
        # voucher_valid_days == 0 → chèque cadeau SANS expiration (valid_until
        # NULL). Une valeur > 0 réintroduit une date limite.
        valid_until = (
            now + timedelta(days=cfg.voucher_valid_days)
            if cfg.voucher_valid_days > 0 else None
        )
        voucher_value = cfg.voucher_value_cents / 100.0
        created_codes: list[str] = []
        for _ in range(crossed):
            code = await _draw_unique_code(self.db, "LOYAL")
            self.db.add(Coupon(
                code=code,
                client_id=transaction.client_id,
                discount_type=CouponDiscountType.amount,
                discount_value=voucher_value,
                source=CouponSource.loyalty_milestone,
                valid_from=now,
                valid_until=valid_until,
                is_active=True,
                notes=(
                    f"Chèque cadeau fidélité {voucher_value:g} € — palier "
                    f"{cfg.voucher_threshold} pts (tx #{transaction.transaction_number})"
                ),
            ))
            created_codes.append(code)

        # Notification cliente : un chèque cadeau vient d'être généré. Best-effort
        # (email + SMS si opt-in) — n'échoue jamais la vente.
        await self.db.flush()
        for code in created_codes:
            try:
                await self._notify_loyalty_voucher(
                    transaction.client_id, code, voucher_value, valid_until
                )
            except Exception as exc:  # noqa: BLE001
                logger.warning(
                    "Loyalty voucher notification failed for tx=%s code=%s: %s",
                    transaction.id, code, exc,
                )

    async def _notify_loyalty_voucher(
        self,
        client_id: uuid.UUID,
        code: str,
        value_eur: float,
        valid_until: datetime | None,
    ) -> None:
        """Prévient la cliente qu'un chèque cadeau fidélité a été généré.

        Information contractuelle (mouvement de cagnotte) → envoyée même sans
        opt-in marketing ; seul l'absence de contact (email/téléphone) arrête.
        Email prioritaire (template ``loyalty_voucher``, éditable), SMS si la
        cliente n'a pas d'email mais un téléphone.
        """
        from app.models.client import Client
        from app.services.communications import log_communication, render_template

        client = (
            await self.db.execute(select(Client).where(Client.id == client_id))
        ).scalar_one_or_none()
        if client is None:
            return

        # valid_until NULL = chèque cadeau sans expiration.
        valide_jusqu_au = (
            f"jusqu'au {valid_until.date().strftime('%d/%m/%Y')}"
            if valid_until else "sans date d'expiration"
        )
        prenom = (client.first_name or "").strip() or "Bonjour"
        context = {
            "prenom": prenom,
            "valeur": f"{value_eur:g}",
            "code_bon": code,
            "valide_jusqu_au": valide_jusqu_au,
        }

        if client.email:
            from app.services.email_gateway import (
                EmailDeliveryError,
                EmailMessage,
                send_email,
            )

            rendered = await render_template(
                self.db,
                "loyalty_voucher",
                context,
                fallback_subject="🎁 Vintiz — votre chèque cadeau fidélité de {valeur} €",
                fallback_html=(
                    "<p>Bonjour {prenom},</p>"
                    "<p>Félicitations ! Vous avez atteint 100 points de fidélité. "
                    "Un <strong>chèque cadeau de {valeur} €</strong> (code "
                    "<strong>{code_bon}</strong>) vient d'être crédité sur votre "
                    "compte. Valable {valide_jusqu_au}, à présenter en "
                    "caisse lors de votre prochain passage.</p>"
                ),
                fallback_text=(
                    "Bonjour {prenom}, vous avez atteint 100 points : un chèque "
                    "cadeau de {valeur} € (code {code_bon}) a été crédité sur votre "
                    "compte. Valable {valide_jusqu_au}."
                ),
            )
            status = "sent"
            backend = "simulation"
            try:
                outcome = send_email(EmailMessage(
                    to=client.email,
                    to_name=client.first_name or None,
                    subject=rendered.subject or "Vintiz — votre chèque cadeau fidélité",
                    html=rendered.html or "",
                    text=rendered.text or "",
                    tags=["loyalty-voucher"],
                ))
                status = outcome.status
                backend = outcome.backend
            except EmailDeliveryError as exc:
                status = "failed"
                backend = "error"
                logger.warning("loyalty_voucher email failed for %s: %s", client.email, exc)
            await log_communication(
                self.db,
                client_id=client.id,
                channel="email",
                kind="loyalty_voucher",
                status=status,
                to_address=client.email,
                subject=rendered.subject,
                backend=backend,
                template_key=rendered.template_key,
            )
        elif client.phone:
            from app.services.sms_gateway import SMSMessage, send_sms

            body = (
                f"Vintiz : bravo {prenom} ! 100 pts atteints. Cheque cadeau de "
                f"{value_eur:g} EUR (code {code}) credite sur votre compte, "
                f"valable {valide_jusqu_au}."
            )
            outcome = send_sms(SMSMessage(to=client.phone, body=body))
            await log_communication(
                self.db,
                client_id=client.id,
                channel="sms",
                kind="loyalty_voucher",
                status=getattr(outcome, "status", "sent"),
                to_address=client.phone,
                subject=None,
                backend=getattr(outcome, "backend", "simulation"),
            )
