async def _build_full_receipt_text(
    db: AsyncSession, transaction_id: uuid.UUID
) -> str | None:
    """Construit le texte du ticket de caisse comme à l'impression.

    Réutilise ``ReceiptService.generate_receipt_text`` + le template
    par défaut + le contexte fidélité pour que l'email reçu par la
    cliente soit le calque exact de l'impression MUNBYN (header, items,
    chips, totaux, paiements, hash NF525, footer fidélité). Retourne
    ``None`` si la transaction n'existe plus côté ORM.
    """
    from app.models.client import Client, LoyaltyTransaction, LoyaltyTxType
    from app.models.pos import Transaction
    from app.models.receipt_template import ReceiptKind, ReceiptTemplate
    from app.services.receipt import ReceiptService

    row = await db.execute(
        select(Transaction).where(Transaction.id == transaction_id)
    )
    tx = row.scalar_one_or_none()
    if tx is None:
        return None

    target_kind = ReceiptKind.invoice if tx.is_invoice else ReceiptKind.ticket
    template = None
    if tx.template_id is not None:
        template = (
            await db.execute(
                select(ReceiptTemplate).where(ReceiptTemplate.id == tx.template_id)
            )
        ).scalar_one_or_none()
    if template is None:
        template = (
            await db.execute(
                select(ReceiptTemplate)
                .where(
                    ReceiptTemplate.kind == target_kind,
                    ReceiptTemplate.is_default.is_(True),
                    ReceiptTemplate.is_active.is_(True),
                )
                .limit(1)
            )
        ).scalar_one_or_none()

    client = None
    loyalty_account = None
    points_earned = None
    if tx.client_id is not None:
        c_row = await db.execute(select(Client).where(Client.id == tx.client_id))
        client = c_row.scalar_one_or_none()
        if client and client.loyalty_account is not None:
            loyalty_account = client.loyalty_account
            earn_row = await db.execute(
                select(LoyaltyTransaction.points)
                .where(
                    LoyaltyTransaction.account_id == loyalty_account.id,
                    LoyaltyTransaction.tx_type == LoyaltyTxType.earn,
                    LoyaltyTransaction.description == f"Sale #{tx.transaction_number}",
                )
            )
            points_earned = earn_row.scalar_one_or_none() or 0

    return ReceiptService().generate_receipt_text(
        tx,
        client=client,
        loyalty_account=loyalty_account,
        points_earned_on_sale=points_earned,
        template=template,
    )


@router.post("/transactions/{transaction_id}/resend")
async def resend_transaction(
    transaction_id: uuid.UUID,
    request: ResendRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(manager_only),
):
    """Resend a transaction receipt by email or SMS.

    Manager-only: the receipt payload contains client PII (name, email,
    purchased items). A staff or magic-link client JWT must not be able to
    pull arbitrary tickets by guessing transaction UUIDs.
    """
    pos_service = PosService(db)
    transaction = await pos_service.get_transaction(transaction_id)
    if not transaction:
        raise HTTPException(status_code=404, detail="Transaction introuvable")
    logger.info(
        "Receipt resend requested by user=%s for transaction=%s channel=%s ad_hoc=%s",
        current_user.id, transaction_id, request.channel, bool(request.to),
    )

    client = transaction.get("client") or {}
    ad_hoc_to = (request.to or "").strip() or None
    # Greeting derived from the linked client first name when present;
    # falls back to a neutral wording for ad-hoc recipients.
    greeting_name = client.get("first_name") if client else None

    if not ad_hoc_to and not client:
        raise HTTPException(
            status_code=400,
            detail="Aucun client associe a cette transaction — fournissez 'to'",
        )

    ticket_num = transaction["transaction_number"]
    total = transaction["total_ttc"]
    items_text = "\n".join(
        f"  - {item['name']} x{item['quantity']} : {item['unit_price']:.2f} EUR"
        for item in transaction.get("items", [])
    )

    # Resolve the active default ticket template + shop name so the email/SMS
    # wording is configurable from the studio (unified with the printed ticket).
    from sqlalchemy import select as _select

    from app.models.receipt_template import ReceiptKind, ReceiptTemplate
    from app.services.app_config import get_section as _get_section

    notif_template = (
        await db.execute(
            _select(ReceiptTemplate)
            .where(
                ReceiptTemplate.kind == ReceiptKind.ticket,
                ReceiptTemplate.is_default.is_(True),
                ReceiptTemplate.is_active.is_(True),
            )
            .limit(1)
        )
    ).scalar_one_or_none()
    _shop_name = (_get_section("shop_info") or {}).get("name", "Vintiz")
    notif_ctx = {
        "ticket_number": str(ticket_num),
        "total_ttc": f"{total:.2f} €",
        "shop_name": _shop_name,
        "client_name": greeting_name or "",
    }

    if request.channel == "email":
        recipient = ad_hoc_to or client.get("email")
        if not recipient:
            raise HTTPException(
                status_code=400,
                detail="Adresse email manquante (ni client, ni 'to' fourni)",
            )
        from app.services.email_gateway import (
            EmailDeliveryError,
            EmailMessage,
            send_email as _gateway_send,
        )

        # Reproduit le ticket de caisse identique à l'impression : on
        # passe par ``ReceiptService.generate_receipt_text`` (même rendu
        # que le ``GET /receipt`` et que l'ESC/POS) plutôt que par un
        # résumé tronqué. Le bandeau d'intro reste configurable côté
        # studio via le template ``ticket``.
        salutation = f"Bonjour {greeting_name}" if greeting_name else "Bonjour"
        if notif_template and notif_template.email_body:
            intro = _apply_placeholders(notif_template.email_body, notif_ctx)
        else:
            intro = (
                f"{salutation},\n\n"
                f"Voici le reçu de votre achat chez {notif_ctx['shop_name']}."
            )
        full_receipt = await _build_full_receipt_text(db, transaction_id)
        if full_receipt:
            body_text = f"{intro}\n\n{full_receipt}"
        else:
            # Fallback ligne-à-ligne si la transaction ORM ne charge pas
            # (cas extrême — la transaction vient d'être supprimée entre
            # le get + le resend) : on garde l'ancien résumé.
            body_text = (
                f"{intro}\n\n"
                f"Ticket #{ticket_num}\n"
                f"Articles :\n{items_text}\n\n"
                f"Total TTC : {total:.2f} EUR"
            )
        subject = (
            _apply_placeholders(notif_template.email_subject, notif_ctx)
            if notif_template and notif_template.email_subject
            else f"Votre reçu {notif_ctx['shop_name']} #{ticket_num}"
        )
        body_html = "<pre style=\"font-family: monospace\">" + body_text + "</pre>"

        try:
            outcome = _gateway_send(EmailMessage(
                to=recipient,
                to_name=greeting_name,
                subject=subject,
                html=body_html,
                text=body_text,
            ))
        except EmailDeliveryError:
            logger.exception("Failed to send receipt email for transaction %s",
                             transaction_id)
            raise HTTPException(
                status_code=502,
                detail="L'envoi de l'email a échoué. Réessayez plus tard.",
            )
        logger.info("Receipt email %s for transaction %s via %s",
                    outcome.status, transaction_id, outcome.backend)
        simulated = outcome.status != "sent"
        return {
            "success": True,
            "status": outcome.status,
            "simulated": simulated,
            "channel": "email",
            "to": recipient,
            "backend": outcome.backend,
            "message": (
                f"Email envoyé à {recipient}"
                if not simulated
                else (
                    f"⚠ Email simulé (provider non configuré). "
                    f"Le destinataire {recipient} N'A PAS reçu le ticket. "
                    f"Configurez Brevo ou SMTP dans /settings > Communication."
                )
            ),
        }

    elif request.channel == "sms":
        recipient = ad_hoc_to or client.get("phone")
        if not recipient:
            raise HTTPException(
                status_code=400,
                detail="Numéro de téléphone manquant (ni client, ni 'to' fourni)",
            )
        # Single SMS gateway covering Brevo (primary) + Twilio (legacy
        # fallback) + simulation. The /resend response shape mirrors the
        # email branch so the front shows a consistent warning bandeau
        # when the send was only simulated.
        from app.services.sms_gateway import (
            SMSDeliveryError,
            SMSMessage,
            send_sms as _gateway_send_sms,
        )

        sms_body = (
            _apply_placeholders(notif_template.sms_body, notif_ctx)
            if notif_template and notif_template.sms_body
            else f"{notif_ctx['shop_name']} - Ticket #{ticket_num} - Total {total:.2f}EUR. Merci !"
        )
        try:
            sms_result = _gateway_send_sms(SMSMessage(to=recipient, body=sms_body))
        except SMSDeliveryError as exc:
            logger.exception(
                "Receipt SMS gateway failed for transaction %s: %s",
                transaction_id, exc,
            )
            raise HTTPException(
                status_code=502,
                detail=f"L'envoi SMS a échoué ({str(exc)[:160]})",
            )
        logger.info(
            "Receipt SMS %s for transaction %s via %s",
            sms_result.status, transaction_id, sms_result.backend,
        )
        simulated = sms_result.status != "sent"
        return {
            "success": True,
            "status": sms_result.status,
            "simulated": simulated,
            "channel": "sms",
            "to": recipient,
            "backend": sms_result.backend,
            "message": (
                f"SMS envoyé au {recipient}"
                if not simulated
                else (
                    f"⚠ SMS simulé (aucun provider configuré). "
                    f"Le destinataire {recipient} N'A PAS reçu le ticket. "
                    f"Renseignez BREVO_API_KEY dans /settings > Communication."
                )
            ),
        }
    else:
        raise HTTPException(status_code=400, detail="Canal invalide (email ou sms)")


