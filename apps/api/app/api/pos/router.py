@router.post("/transactions/{transaction_id}/print")
async def print_transaction_receipt(
    transaction_id: uuid.UUID,
    kick_drawer: bool = True,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Send the receipt to the MUNBYN ESC/POS printer (TCP 9100).

    ``kick_drawer=false`` désactive l'ouverture automatique du tiroir-caisse
    lors d'une réimpression (la vente initiale a déjà fait son office, on
    veut juste une copie du ticket pour la cliente — pas de nouveau coup
    de tiroir).
    """
    from sqlalchemy import select
    from sqlalchemy.orm import selectinload

    from app.models.pos import PaymentMethod, Transaction
    from app.services import escpos_service
    from app.services.hardware_config import load_config

    result = await db.execute(
        select(Transaction)
        .options(selectinload(Transaction.items), selectinload(Transaction.payments))
        .where(Transaction.id == transaction_id)
    )
    transaction = result.scalar_one_or_none()
    if not transaction:
        raise HTTPException(status_code=404, detail="Transaction introuvable")

    cfg = load_config()
    rp = cfg["receipt_printer"]
    if not rp.get("enabled"):
        raise HTTPException(status_code=400, detail="Imprimante de recus desactivee dans les parametres")
    host = rp.get("host") or ""
    port = int(rp.get("port") or 9100)
    if not host:
        raise HTTPException(status_code=400, detail="Adresse IP de l'imprimante non configuree")

    template, shop = await _resolve_ticket_template_and_shop(db, transaction)
    try:
        escpos_service.print_receipt(
            transaction,
            host=host,
            port=port,
            template=template,
            shop=shop,
            width=int(rp.get("width_chars") or 42),
            cut=bool(rp.get("cut_paper", True)),
        )
    except Exception as exc:  # noqa: BLE001
        raise HTTPException(status_code=502, detail=f"Imprimante injoignable : {exc}") from exc

    # Auto-kick drawer if cash payment and drawer enabled. The kick is best
    # effort (the printer was reachable just above), but a silent failure
    # would leave the drawer closed on a cash sale without alerting the
    # cashier — accounting risk. Surface the outcome in the response and
    # log the full traceback if the kick fails.
    drawer_kick_ok: bool | None = None
    drawer_error: str | None = None
    drawer_cfg = cfg["cash_drawer"]
    if kick_drawer and drawer_cfg.get("enabled") and drawer_cfg.get("kick_on_cash"):
        has_cash = any(
            (p.method == PaymentMethod.cash)
            for p in (transaction.payments or [])
        )
        if has_cash:
            try:
                escpos_service.kick_drawer(
                    host,
                    port,
                    pin=int(drawer_cfg.get("kick_pin") or 0),
                    on_time=int(drawer_cfg.get("on_time_ms") or 50),
                    off_time=int(drawer_cfg.get("off_time_ms") or 250),
                )
                drawer_kick_ok = True
            except Exception as exc:  # noqa: BLE001
                drawer_kick_ok = False
                drawer_error = str(exc)
                logger.exception(
                    "Cash drawer kick failed for transaction %s on %s:%s",
                    transaction_id, host, port,
                )

    # Trace audit : on logge chaque impression pour qu'un manager puisse
    # voir « combien de copies du ticket #N ont été émises et par qui ».
    # NF525 n'oblige pas à versionner les réimpressions (le ticket original
    # reste hash-signé), mais c'est utile pour distinguer une fraude
    # potentielle (réimpressions multiples « par hasard ») d'une demande
    # cliente légitime.
    db.add(
        AuditLog(
            user_id=current_user.id,
            action="receipt.reprint",
            entity="transaction",
            entity_id=transaction_id,
            data={"kick_drawer": kick_drawer},
        )
    )
    await db.commit()

    response: dict = {"success": True, "transaction_id": str(transaction_id)}
    if drawer_kick_ok is not None:
        response["drawer_kicked"] = drawer_kick_ok
        if drawer_error:
            response["drawer_error"] = drawer_error
    return response


@router.get("/transactions/{transaction_id}/escpos")
async def get_transaction_escpos(
    transaction_id: uuid.UUID,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
    kick_drawer: bool = False,
):
    """Return the raw ESC/POS byte stream for the receipt.

    Used by the WebUSB flow on the cashier tablet (Lenovo Idea Tab Pro):
    the front fetches these bytes and pipes them to the MUNBYN directly
    over USB-OTG, bypassing the backend's TCP socket. Same ``build_receipt``
    helper as the network path, so the printed output is identical.

    Pass ``kick_drawer=true`` to append the ``ESC p`` drawer pulse at the
    end of the payload (used on cash sales when the drawer is wired to
    the printer's RJ-12 port).
    """
    from sqlalchemy import select
    from sqlalchemy.orm import selectinload
    from fastapi.responses import Response

    from app.models.pos import PaymentMethod, Transaction
    from app.services import escpos_service
    from app.services.hardware_config import load_config

    result = await db.execute(
        select(Transaction)
        .options(selectinload(Transaction.items), selectinload(Transaction.payments))
        .where(Transaction.id == transaction_id)
    )
    transaction = result.scalar_one_or_none()
    if not transaction:
        raise HTTPException(status_code=404, detail="Transaction introuvable")

    cfg = load_config()
    rp = cfg["receipt_printer"]
    template, shop = await _resolve_ticket_template_and_shop(db, transaction)
    payload = escpos_service.build_receipt(
        transaction,
        template=template,
        shop=shop,
        width=int(rp.get("width_chars") or 42),
        cut=bool(rp.get("cut_paper", True)),
    )
    # Only kick the drawer when the caller asked AND the sale actually took
    # cash — same guard as the network /print path. A card/cheque sale must
    # not pop the till open (no cash changed hands → accounting/security risk).
    has_cash = any(
        (p.method == PaymentMethod.cash) for p in (transaction.payments or [])
    )
    if kick_drawer and has_cash:
        drawer_cfg = cfg["cash_drawer"]
        payload += escpos_service.build_drawer_kick(
            pin=int(drawer_cfg.get("kick_pin") or 0),
            on_time=int(drawer_cfg.get("on_time_ms") or 50),
            off_time=int(drawer_cfg.get("off_time_ms") or 250),
        )
    return Response(
        content=bytes(payload),
        media_type="application/octet-stream",
        headers={
            "Content-Disposition": f'attachment; filename="receipt-{transaction_id}.bin"',
            "Cache-Control": "no-store",
        },
    )


