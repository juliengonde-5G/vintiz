@router.post("/drawer/open")
async def open_drawer(
    request: OpenDrawerRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Open cash drawer for the day."""
    pos_service = PosService(db)
    breakdown = (
        [item.model_dump() for item in request.opening_breakdown]
        if request.opening_breakdown
        else None
    )
    drawer = await pos_service.open_drawer(
        current_user.id,
        request.opening_amount,
        cashier_id=request.cashier_id,
        opening_breakdown=breakdown,
    )

    from app.models.events import EventSource, EventType
    await EventService(db).emit(
        EventType.cashier_session_opened,
        source=EventSource.pos,
        user_id=current_user.id,
        meta={
            "drawer_id": str(drawer.id),
            "cashier_id": str(request.cashier_id) if request.cashier_id else None,
            "opening_amount": float(drawer.opening_amount),
        },
    )

    return {
        "drawer_id": str(drawer.id),
        "opening_amount": float(drawer.opening_amount),
    }


@router.post("/drawer/close")
async def close_drawer(
    request: CloseDrawerRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Close cash drawer and generate Z report."""
    pos_service = PosService(db)
    fiscal_service = FiscalService(db)

    closing_breakdown = (
        [item.model_dump() for item in request.closing_breakdown]
        if request.closing_breakdown
        else None
    )
    drawer = await pos_service.close_drawer(
        current_user.id,
        request.closing_amount,
        cashier_id=request.cashier_id,
        closing_breakdown=closing_breakdown,
        closing_note=request.closing_note,
        allowed_discrepancy_override=request.allowed_discrepancy_override,
    )
    z_report = await fiscal_service.generate_z_report(
        drawer, current_user.id, cashier_id=request.cashier_id
    )

    from app.models.events import EventSource, EventType
    discrepancy = (
        float(drawer.closing_amount) - float(drawer.expected_amount)
        if drawer.expected_amount is not None and drawer.closing_amount is not None
        else None
    )
    await EventService(db).emit(
        EventType.cashier_session_closed,
        source=EventSource.pos,
        user_id=current_user.id,
        meta={
            "drawer_id": str(drawer.id),
            "cashier_id": str(drawer.cashier_id) if drawer.cashier_id else None,
            "z_report_number": z_report.report_number,
            "discrepancy": discrepancy,
            "transaction_count": z_report.transaction_count,
        },
    )

    # Clôture comptable — best-effort (n'empêche pas la réponse en cas d'échec)
    accounting_export_id = None
    accounting_status = None
    try:
        from app.services.accounting_service import AccountingService
        acct_svc = AccountingService(db)
        acct_exp = await acct_svc.run_daily_close(
            z_report=z_report,
            drawer=drawer,
            triggered_by_user_id=current_user.id,
        )
        accounting_export_id = str(acct_exp.id)
        accounting_status = acct_exp.status.value
    except Exception as _acct_exc:
        import logging
        logging.getLogger("vintiz").error("Accounting close failed: %s", _acct_exc)

    return {
        "drawer_id": str(drawer.id),
        "z_report_number": z_report.report_number,
        "total_sales": float(z_report.total_sales),
        "total_refunds": float(z_report.total_refunds),
        "total_net": float(z_report.total_net),
        "transaction_count": z_report.transaction_count,
        "difference": float(drawer.closing_amount - drawer.expected_amount)
        if drawer.expected_amount
        else 0,
        "accounting_export_id": accounting_export_id,
        "accounting_status": accounting_status,
    }


