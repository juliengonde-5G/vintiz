@router.post("/z-reports/regularization")
async def create_regularization(
    request: RegularizationRequest,
    background_tasks: BackgroundTasks,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(manager_only),
):
    """Établit un Z de régularisation pour une journée d'ouverture oubliée.

    Le Z est créé à sa date réelle, numéroté à la suite et chaîné sur le
    dernier Z (chaîne NF525 intacte, jamais antidatée). Il couvre uniquement
    les ventes orphelines (hors de toute session de caisse) ; refus 409 en cas
    de chevauchement avec une session existante.

    Si ``close_open_drawers`` est vrai, on clôture d'abord toute caisse restée
    ouverte (chacune génère son Z) — ce qui débloque l'ouverture du jour. Si la
    clôture a déjà capté les ventes de la journée, il ne reste alors rien à
    régulariser (pas d'erreur).

    Chaque Z produit (régularisation + caisses clôturées) déclenche en tâche de
    fond la clôture comptable (AccountingService.run_daily_close) → génération
    de l'export comptable + du FEC quotidien, exactement comme une clôture
    normale.
    """
    start, end = _day_bounds_utc(request.date)
    fiscal = FiscalService(db)

    closed_reports: list = []
    if request.close_open_drawers:
        closed_reports = await fiscal.close_open_drawers(current_user.id)

    # (z_report_id, cash_drawer_id) pour l'export comptable / FEC en tâche de fond.
    accounting_jobs: list[tuple] = [(r.id, r.cash_drawer_id) for r in closed_reports]

    reg: dict | None = None
    try:
        z = await fiscal.create_regularization_z(
            start, end, request.reason, current_user.id
        )
        await db.refresh(z)
        accounting_jobs.append((z.id, z.cash_drawer_id))
        reg = {
            "z_report_number": z.report_number,
            "id": str(z.id),
            "is_regularization": True,
            "total_sales": float(z.total_sales),
            "total_refunds": float(z.total_refunds),
            "total_net": float(z.total_net),
            "transaction_count": z.transaction_count,
            "period": request.date,
        }
    except HTTPException as exc:
        # Après une clôture, il est NORMAL qu'il ne reste rien d'orphelin (la
        # caisse fermée a capté la journée) ou que tout soit « couvert » : on ne
        # remonte pas d'erreur dans ce cas, la clôture est l'action utile.
        if closed_reports and exc.status_code in (400, 409):
            reg = None
        else:
            raise

    await db.commit()

    # Export comptable + FEC quotidien pour chaque Z, en arrière-plan (Pennylane
    # HTTP + email peuvent être lents). Idempotent par z_report_id.
    for z_id, drawer_id in accounting_jobs:
        background_tasks.add_task(
            _run_accounting_close_in_bg,
            z_report_id=z_id,
            drawer_id=drawer_id,
            user_id=current_user.id,
        )

    logger.info(
        "Régularisation %s : %d caisse(s) clôturée(s), reg=%s, %d export(s) FEC programmé(s) (user=%s, motif=%s)",
        request.date, len(closed_reports), bool(reg), len(accounting_jobs),
        current_user.id, request.reason,
    )
    return {
        "closed_z_reports": [
            {"z_report_number": r.report_number, "id": str(r.id)} for r in closed_reports
        ],
        "regularization": reg,
        "fec_exports_scheduled": len(accounting_jobs),
        # Compat champ historique (présent si une régularisation a été établie).
        **(reg or {}),
    }


class CBInitiateRequest(BaseModel):
    amount: float = Field(gt=0, le=999_999)
    description: str = Field(default="Vente Vintiz", min_length=1, max_length=255)
    # POS idempotence key (Transaction.client_uuid). Forwarded to SumUp as
    # affiliate.foreign_transaction_id so a retried initiate references the
    # same intended payment and the resulting transaction can be looked up
    # for reconciliation/refund.
    foreign_transaction_id: str | None = Field(default=None, max_length=120)
    # Cashier + drawer context, so the authoritative PaymentAttempt created
    # server-side at initiation is attributed correctly (the POS no longer
    # has to create the attempt itself — it only updates it).
    cashier_id: uuid.UUID | None = None
    drawer_id: uuid.UUID | None = None


class ResendRequest(BaseModel):
    channel: str  # 'email' or 'sms'
    # Optional ad-hoc recipient (walk-in customer with no CRM record).
    # When set, overrides the client's stored email/phone on the
    # transaction. When omitted, the linked client's email/phone is used
    # as before.
    to: str | None = None


