class CartItem(BaseModel):
    product_id: uuid.UUID | None = None
    # Article permanent (catalogue libre, quantité illimitée). Mutuellement
    # exclusif avec ``product_id`` — exactement zéro ou un des deux est posé.
    # Les lignes manuelles (sac, custom) laissent les deux à None.
    permanent_item_id: uuid.UUID | None = None
    name: str | None = Field(default=None, max_length=255)
    quantity: int = Field(default=1, ge=1, le=999)
    unit_price: float | None = Field(default=None, gt=0, le=999_999)
    discount_percent: float = Field(default=0, ge=0, lt=100)


class PaymentInput(BaseModel):
    method: str = Field(min_length=2, max_length=20)  # cash, card, cheque
    amount: Decimal = Field(gt=0, max_digits=10, decimal_places=2)
    attempt_id: uuid.UUID | None = None
    # SumUp identifiers captured when a card payment reaches PAID. Persisted
    # on the Payment row so a later card refund can be issued via the SumUp
    # API (without these, every CB refund falls back to manual). Optional —
    # only set on card tenders.
    sumup_checkout_id: str | None = Field(default=None, max_length=100)
    sumup_transaction_id: str | None = Field(default=None, max_length=64)
    sumup_transaction_code: str | None = Field(default=None, max_length=32)
    sumup_auth_code: str | None = Field(default=None, max_length=16)
    sumup_card_brand: str | None = Field(default=None, max_length=32)
    sumup_card_last4: str | None = Field(default=None, pattern=r"^\d{4}$")
    sumup_environment: str | None = Field(default=None, max_length=16)
    # Bon cadeau d'ouverture affecté comme moyen de paiement (method=voucher) :
    # code du bon (Coupon source=event_opening) à valider + consommer sur la vente.
    voucher_code: str | None = Field(default=None, max_length=64)


class CreateTransactionRequest(BaseModel):
    items: list[CartItem] = Field(min_length=1, max_length=500)
    payments: list[PaymentInput] = Field(min_length=1, max_length=20)
    client_id: uuid.UUID | None = None
    cashier_id: uuid.UUID | None = None
    # Idempotence key generated by the POS UI (P1-005). When supplied,
    # a duplicate POST returns the original transaction.
    client_uuid: uuid.UUID | None = None
    # Optional coupon code to redeem atomically with the sale (P4-008).
    coupon_code: str | None = Field(default=None, max_length=64)
    # B2B invoice mode (PR 2/6 — POS routine SumUp). When True, the API
    # assigns a separate ``invoice_number`` (FACT-{year}-{seq:06d}) and
    # snapshots the buyer block + template id on the transaction so the
    # invoice PDF reproduces the historical document byte-identical.
    is_invoice: bool = False
    client_siret: str | None = None
    client_company_name: str | None = None
    client_billing_address: str | None = None
    template_id: uuid.UUID | None = None
    # Plafond espèces (CMF art. L.112-6, décret 2015-741). 1 000 € pour
    # un résident fiscal FR, 15 000 € pour un touriste non-résident.
    # ``customer_is_tourist`` doit être attesté par un justificatif
    # d'identité étranger vérifié en boutique.
    customer_is_tourist: bool = False
    # Override manager du plafond espèces : motif obligatoire, manager
    # uniquement, tracé en audit log.
    cash_override_reason: str | None = None
    # PS 360 V2 — réponse à la micro-question caisse « Cet achat est-il pour
    # vous ? ». True = cadeau → gardé pour le CA + la fidélité mais exclu du
    # profil de goûts (un cadeau pollue le centroïde).
    is_gift: bool = False


