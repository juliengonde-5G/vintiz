@router.post("/payments/cb/initiate")
async def initiate_cb_payment(
    request: CBInitiateRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Initiate a SumUp card checkout. Returns checkout_id for polling.

    The backend is the authoritative recorder of the attempt: it creates the
    ``PaymentAttempt`` (pending, or failed when SumUp rejects the initiation)
    and returns its ``attempt_id`` so the POS only *updates* the lifecycle. A
    CB sale therefore leaves a server-side trace even if the browser dies —
    that trace is what surfaces in « CB échouées ». Every HTTP call to SumUp
    is mirrored into the ``sumup_exchanges`` diagnostic log.
    """
    from app.models.payment_attempt import PaymentAttempt, PaymentAttemptStatus
    from app.models.pos import PaymentMethod
    from app.services.sumup_exchange_log import persist_sumup_exchanges
    from app.services.sumup_service import SumUpService

    svc = SumUpService()
    if not svc.is_configured or not svc.merchant_code:
        raise HTTPException(status_code=503, detail="SumUp n'est pas configuré.")
    if settings.is_production and svc.is_sandbox:
        raise HTTPException(
            status_code=503,
            detail="Une clé SumUp de test est interdite en production.",
        )
    await svc.resolve_reader_from_registry(db)
    result = await svc.create_checkout(
        amount=request.amount,
        description=request.description,
        foreign_transaction_id=request.foreign_transaction_id,
    )

    status_raw = str(result.get("status", "PENDING")).upper()
    mode = result.get("mode")
    failed = status_raw == "FAILED"

    # Debug aid for « les transactions n'aboutissent pas vers le terminal » :
    # a checkout created in link mode (no reader resolved) will NOT ring the
    # Solo. Flag it loudly so the cashier/manager understands why the TPE
    # stays silent instead of waiting out the 90 s front-end timeout.
    if not failed and mode == "checkout":
        result["reader_targeted"] = False
        result["diagnostic"] = (
            "Aucun TPE ciblé : paiement créé en mode lien — le terminal Solo ne "
            "sonnera pas. Déclarez un terminal par défaut dans Paramètres › "
            "Caisse (ou renseignez SUMUP_READER_ID)."
        )
    elif mode == "reader":
        result["reader_targeted"] = True

    # Authoritative PaymentAttempt — created here, then updated by the POS via
    # /payment-attempts using the returned attempt_id.
    attempt = PaymentAttempt(
        method=PaymentMethod.card,
        amount=float(request.amount),
        status=(
            PaymentAttemptStatus.failed if failed else PaymentAttemptStatus.pending
        ),
        cashier_id=request.cashier_id or current_user.id,
        drawer_id=request.drawer_id,
        sumup_checkout_id=result.get("checkout_id"),
        foreign_transaction_id=request.foreign_transaction_id,
        error_detail=(
            redact_sumup_error(
                result.get("error_detail") or result.get("error_friendly") or "Refusé par SumUp"
            )
            if failed
            else None
        ),
    )
    db.add(attempt)
    await db.flush()
    await db.refresh(attempt)
    result["attempt_id"] = str(attempt.id)

    # Offline groundwork : a *recoverable* CB failure (terminal offline/busy,
    # SumUp outage, network) is queued for automatic retry so the sale isn't
    # simply lost. Definitive failures (bad key, unknown reader, unconfigured)
    # carry no ``recoverable`` flag and are not queued — configuring is the fix.
    if failed and result.get("recoverable"):
        from app.services.failed_payment_service import FailedPaymentService

        fp = await FailedPaymentService().create_failed_payment(
            db,
            amount=float(request.amount),
            checkout_reference=str(
                result.get("checkout_reference") or result.get("checkout_id") or ""
            ),
            error_detail=result.get("error_detail") or result.get("error_friendly"),
            foreign_transaction_id=request.foreign_transaction_id,
            description=request.description,
            reader_id=result.get("reader_id"),
            cashier_id=request.cashier_id or current_user.id,
            is_recoverable=True,
        )
        result["failed_payment_id"] = str(fp.id)

    await persist_sumup_exchanges(db, svc, prune=True)
    return result


@router.get("/payments/cb/{checkout_id}/status")
async def get_cb_payment_status(
    checkout_id: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Poll the status of a SumUp checkout."""
    from app.services.sumup_exchange_log import persist_sumup_exchanges
    from app.services.sumup_service import SumUpService
    svc = SumUpService()
    result = await svc.get_checkout_status(checkout_id)

    # Avoid flooding the diagnostic log with identical PENDING polls (one
    # every ~1.5 s for up to 90 s): only persist a status exchange when it
    # carries signal — a terminal outcome or an HTTP/transport error.
    status_norm = str(result.get("status", "PENDING")).upper()
    interesting = status_norm != "PENDING" or any(
        not e.get("ok") for e in svc.exchanges
    )
    if interesting:
        await persist_sumup_exchanges(db, svc)
    else:
        svc.drain_exchanges()
    return result


@router.get("/payments/cb/recover")
async def recover_cb_payment(
    foreign_transaction_id: str,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Vérifie, par la référence de la vente, si la carte a DÉJÀ été débitée.

    Second canal de confirmation, INDÉPENDANT du polling checkout : interroge
    SumUp par ``foreign_transaction_id`` (= client_uuid de la vente) pour
    savoir si un paiement a abouti. Sert à récupérer une confirmation TPE
    perdue (« la caisse ne reçoit pas le retour du terminal ») AVANT de
    réencaisser — évite les doubles paiements. Retourne le statut normalisé
    (PAID / FAILED / PENDING / NOT_FOUND) + les identifiants SumUp si payé.
    """
    from app.services.sumup_exchange_log import persist_sumup_exchanges
    from app.services.sumup_service import SumUpService, _normalize_txn_status

    svc = SumUpService()
    if not svc.is_configured:
        return {"found": False, "status": "UNKNOWN", "configured": False}

    txn = await svc.get_transaction(foreign_transaction_id=foreign_transaction_id)
    await persist_sumup_exchanges(db, svc)
    if not txn:
        return {"found": False, "status": "NOT_FOUND", "configured": True}

    # La réponse peut renvoyer la transaction directement ou dans items[].
    if isinstance(txn, dict) and isinstance(txn.get("items"), list):
        txn = (txn["items"] or [{}])[0] or {}
    raw_status = (txn.get("status") or "").upper()
    norm = _normalize_txn_status(raw_status)
    card = txn.get("card") or {}
    return {
        "found": True,
        "configured": True,
        "status": norm,
        "sumup_status": raw_status,
        "sumup_transaction_id": txn.get("id"),
        "sumup_transaction_code": txn.get("transaction_code"),
        "sumup_auth_code": txn.get("auth_code"),
        "sumup_card_brand": card.get("type") or card.get("scheme"),
        "sumup_card_last4": card.get("last_4_digits"),
        "amount": txn.get("amount"),
    }


