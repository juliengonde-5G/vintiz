    if template is None:
        template = (
            await db.execute(
                select(ReceiptTemplate)
                .where(
                    ReceiptTemplate.kind == ReceiptKind.invoice,
                    ReceiptTemplate.is_default.is_(True),
                    ReceiptTemplate.is_active.is_(True),
                )
                .limit(1)
            )
        ).scalar_one_or_none()

