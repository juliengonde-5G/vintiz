async def _run_accounting_close_in_bg(
    *, z_report_id: uuid.UUID, drawer_id: uuid.UUID, user_id: uuid.UUID
) -> None:
    """Background task : exécute AccountingService.run_daily_close avec sa
    propre session DB.

    Ouvrir une session indépendante évite tout conflit avec celle du
    endpoint (déjà commit + close à ce stade). Les erreurs sont loggées
    mais ne remontent jamais à un utilisateur — c'est de l'export comptable
    asynchrone, le Z-report fiscal est déjà signé en base."""
    from app.core.database import async_session
    from app.models.pos import CashDrawer, ZReport
    from app.services.accounting_service import AccountingService

    try:
        async with async_session() as bg_db:
            z_report = (
                await bg_db.execute(
                    select(ZReport).where(ZReport.id == z_report_id)
                )
            ).scalar_one_or_none()
            drawer = (
                await bg_db.execute(
                    select(CashDrawer).where(CashDrawer.id == drawer_id)
                )
            ).scalar_one_or_none()
            if z_report is None or drawer is None:
                logger.warning(
                    "Accounting BG close skipped: missing z_report=%s or drawer=%s",
                    z_report_id, drawer_id,
                )
                return
            await AccountingService(bg_db).run_daily_close(
                z_report=z_report,
                drawer=drawer,
                triggered_by_user_id=user_id,
            )
    except Exception as exc:  # noqa: BLE001
        logger.exception("Accounting BG close failed: %s", exc)


@router.post("/drawer/close")
async def close_drawer(
    request: CloseDrawerRequest,
    background_tasks: BackgroundTasks,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Close cash drawer and generate Z report.

    La clôture comptable (AccountingService.run_daily_close) — qui inclut
    un export Pennylane (HTTP synchrone, peut hanger) + un email rapport
    SMTP — est désormais déclenchée en tâche de fond. Auparavant elle
    bloquait la réponse plusieurs minutes en cas de TPE/SMTP injoignable,
    provoquant côté navigateur un timeout de proxy → ``Failed to fetch``
    avec un Z-report en réalité **déjà créé** en base. Le manager devait
    rafraîchir pour comprendre. Maintenant, la réponse arrive dès que le
    Z-report est signé, et la trace comptable est complétée en arrière-plan.
    """
    pos_service = PosService(db)
    fiscal_service = FiscalService(db)

    closing_breakdown = (
        [item.model_dump() for item in request.closing_breakdown]
        if request.closing_breakdown
        else None
    )
    drawer = await pos_service.close_drawer(
        current_user.id,
        request.closing_amount,
        cashier_id=request.cashier_id,
        closing_breakdown=closing_breakdown,
        closing_note=request.closing_note,
        allowed_discrepancy_override=request.allowed_discrepancy_override,
    )
    z_report = await fiscal_service.generate_z_report(
        drawer, current_user.id, cashier_id=request.cashier_id
    )

    from app.models.events import EventSource, EventType
    discrepancy = (
        float(drawer.closing_amount) - float(drawer.expected_amount)
        if drawer.expected_amount is not None and drawer.closing_amount is not None
        else None
    )
    await EventService(db).emit(
        EventType.cashier_session_closed,
        source=EventSource.pos,
        user_id=current_user.id,
        meta={
            "drawer_id": str(drawer.id),
            "cashier_id": str(drawer.cashier_id) if drawer.cashier_id else None,
            "z_report_number": z_report.report_number,
            "discrepancy": discrepancy,
            "transaction_count": z_report.transaction_count,
        },
    )
    # Commit explicite avant la background task : la tâche ouvre sa propre
    # session DB et ne verra rien si on attend la cleanup du dependency.
    await db.commit()

    # Clôture comptable en arrière-plan (Pennylane + email — best-effort).
    background_tasks.add_task(
        _run_accounting_close_in_bg,
        z_report_id=z_report.id,
        drawer_id=drawer.id,
        user_id=current_user.id,
    )
    accounting_export_id = None
    accounting_status = "pending_background"

    return {
        "drawer_id": str(drawer.id),
        "z_report_number": z_report.report_number,
        "total_sales": float(z_report.total_sales),
        "total_refunds": float(z_report.total_refunds),
        "total_net": float(z_report.total_net),
        "transaction_count": z_report.transaction_count,
        "difference": float(drawer.closing_amount - drawer.expected_amount)
        if drawer.expected_amount
        else 0,
        "accounting_export_id": accounting_export_id,
        "accounting_status": accounting_status,
    }


@router.get("/drawer/current")
async def get_current_drawer(
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Get the currently open drawer + the live expected cash counter.

    ``expected_cash`` est le fond théorique en caisse à l'instant T :
    fond d'ouverture + encaissements espèces - remboursements espèces +
    apports - prélèvements. Affiché côté POS en permanence pour que la
    caissière voie ce qui devrait être dans le tiroir avant la clôture.
    """
    from datetime import timedelta

    from sqlalchemy import func

    from app.models.cash_movement import CashMovement, CashMovementDirection
    from app.models.pos import Payment, PaymentMethod, Transaction, TransactionType

    pos_service = PosService(db)
    drawer = await pos_service.get_open_drawer()
    if not drawer:
        return {"open": False}

    # Même fenêtre temporelle que ``close_drawer`` pour la cohérence : on
    # tolère 1 s de marge sur ``opened_at`` (SQLite TEXT vs func.now()).
    period_start = drawer.opened_at - timedelta(seconds=1)

    cash_in_sales = Decimal(str((await db.execute(
        select(func.coalesce(func.sum(Payment.amount), 0))
        .join(Transaction, Payment.transaction_id == Transaction.id)
        .where(
            Payment.method == PaymentMethod.cash,
            Transaction.created_at >= period_start,
            Transaction.transaction_type != TransactionType.refund,
        )
    )).scalar_one()))
    cash_out_refunds = Decimal(str((await db.execute(
        select(func.coalesce(func.sum(Payment.amount), 0))
        .join(Transaction, Payment.transaction_id == Transaction.id)
        .where(
            Payment.method == PaymentMethod.cash,
            Transaction.created_at >= period_start,
            Transaction.transaction_type == TransactionType.refund,
        )
    )).scalar_one()))
    inflows = Decimal(str((await db.execute(
        select(func.coalesce(func.sum(CashMovement.amount), 0))
        .where(
            CashMovement.drawer_id == drawer.id,
            CashMovement.direction == CashMovementDirection.inflow,
        )
    )).scalar_one()))
    outflows = Decimal(str((await db.execute(
        select(func.coalesce(func.sum(CashMovement.amount), 0))
        .where(
            CashMovement.drawer_id == drawer.id,
            CashMovement.direction == CashMovementDirection.outflow,
        )
    )).scalar_one()))

    expected = (
        Decimal(str(drawer.opening_amount))
        + cash_in_sales
        - cash_out_refunds
        + inflows
        - outflows
    )

    return {
        "open": True,
        "drawer_id": str(drawer.id),
        "opening_amount": float(drawer.opening_amount),
        "expected_cash": float(expected),
        "cash_in_sales": float(cash_in_sales),
        "cash_out_refunds": float(cash_out_refunds),
        "inflows": float(inflows),
        "outflows": float(outflows),
    }


