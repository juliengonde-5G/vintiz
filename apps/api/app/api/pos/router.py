class RefundLineRequest(BaseModel):
    transaction_item_id: uuid.UUID
    quantity: int


class RefundRequest(BaseModel):
    items: list[RefundLineRequest]
    refund_method: str  # cash | card | cheque | avoir
    cashier_id: uuid.UUID | None = None
    reason: str | None = None
    # Idempotence key (generated by the POS UI per refund). A retried or
    # double-clicked refund replays the same uuid and returns the original
    # refund instead of issuing a second one.
    client_uuid: uuid.UUID | None = None


@router.post("/transactions/{transaction_id}/refund")
async def refund_transaction(
    transaction_id: uuid.UUID,
    request: RefundRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Issue a partial or full refund of a sale.

    Refunded products are returned to display status. The refund total can
    be settled in cash, on card (record only — SumUp call is a TODO), or as
    store credit on the customer's avoir balance.
    """
    refund_service = RefundService(db)
    fiscal_service = FiscalService(db)

    refund_tx = await refund_service.refund_transaction(
        original_tx_id=transaction_id,
        items=[
            RefundLineInput(line.transaction_item_id, line.quantity)
            for line in request.items
        ],
        refund_method=request.refund_method,
        user_id=current_user.id,
        cashier_id=request.cashier_id,
        reason=request.reason,
        client_uuid=request.client_uuid,
    )

    # Idempotent replay: refund_service returned the already-created (and
    # already-signed) refund. Skip re-signing, the SumUp refund, and the
    # events so we never double-refund the customer.
    if request.client_uuid is not None and refund_tx.hash_chain:
        return {
            "id": str(refund_tx.id),
            "transaction_number": refund_tx.transaction_number,
            "transaction_type": refund_tx.transaction_type.value,
            "original_transaction_id": str(refund_tx.original_transaction_id)
            if refund_tx.original_transaction_id
            else None,
            "total_ttc": float(refund_tx.total_ttc),
            "refund_method": request.refund_method,
            "hash_chain": refund_tx.hash_chain,
            "replayed": True,
        }

    # SumUp refund (when refund_method == card AND the original sale
    # was paid by card with a tracked SumUp transaction_id). Without
    # this call, we would refund cash from the till but SumUp would
    # still hold the customer's money — direct accounting loss.
    sumup_refund_status: dict | None = None
    if request.refund_method == "card":
        from sqlalchemy import select
        from sqlalchemy.orm import selectinload
        from app.models.pos import Payment, PaymentMethod, Transaction
        from app.services.sumup_service import SumUpService

        original = (
            await db.execute(
                select(Transaction)
                .options(selectinload(Transaction.payments))
                .where(Transaction.id == transaction_id)
            )
        ).scalar_one_or_none()
        cb_payment = None
        for p in (original.payments if original else []):
            if p.method == PaymentMethod.card and getattr(p, "sumup_transaction_id", None):
                cb_payment = p
                break
        if cb_payment is None:
            raise HTTPException(
                status_code=409,
                detail=(
                    "Aucun paiement SumUp traçable sur la vente d'origine. "
                    "Le remboursement Vintiz n'a pas été enregistré."
                ),
            )
        else:
            svc = SumUpService()
            sumup_refund_status = await svc.refund_transaction(
                cb_payment.sumup_transaction_id,
                amount=float(refund_tx.total_ttc),
            )
            if sumup_refund_status.get("ok"):
                refund_payment = (
                    await db.execute(
                        select(Payment).where(
                            Payment.transaction_id == refund_tx.id,
                            Payment.method == PaymentMethod.card,
                        )
                    )
                ).scalar_one_or_none()
                if refund_payment is not None:
                    refund_payment.sumup_transaction_id = cb_payment.sumup_transaction_id
                    refund_payment.sumup_transaction_code = "REFUND"
                    refund_payment.sumup_environment = (
                        cb_payment.sumup_environment or "production"
                    )
            # Mirror the refund call into the SumUp diagnostic log.
            from app.services.sumup_exchange_log import persist_sumup_exchanges
            await persist_sumup_exchanges(db, svc)
            if not sumup_refund_status.get("ok"):
                raise HTTPException(
                    status_code=502,
                    detail={
                        "code": "sumup_refund_failed",
                        "message": (
                            "SumUp n'a pas confirmé le remboursement. "
                            "Aucun retour fiscal Vintiz n'a été validé."
                        ),
                        "sumup": sumup_refund_status,
                    },
                )

    # The fiscal refund only exists after the external card refund is
    # confirmed. Any exception above rolls back stock, avoir and loyalty.
    await fiscal_service.sign_transaction(refund_tx)

    # Emit a product.refunded event per refunded item (P1-003).
    from app.models.events import EventSource, EventType
    events = EventService(db)
    for item in (refund_tx.items or []):
        if item.product_id is None:
            continue
        await events.emit(
            EventType.product_refunded,
            source=EventSource.pos,
            customer_id=refund_tx.client_id,
            product_id=item.product_id,
            transaction_id=refund_tx.id,
            user_id=current_user.id,
            meta={
                "quantity": int(item.quantity),
                "refund_method": request.refund_method,
                "reason": request.reason,
                "original_transaction_id": str(refund_tx.original_transaction_id),
            },
        )

    return {
        "id": str(refund_tx.id),
        "transaction_number": refund_tx.transaction_number,
        "transaction_type": refund_tx.transaction_type.value,
        "original_transaction_id": str(refund_tx.original_transaction_id)
        if refund_tx.original_transaction_id
        else None,
        "total_ttc": float(refund_tx.total_ttc),
        "refund_method": request.refund_method,
        "hash_chain": refund_tx.hash_chain,
        # When the refund went through SumUp, the front renders a green
        # success ; when it didn't (offline, untracked payment), it
        # renders a yellow warning instructing the operator to issue
        # the SumUp refund manually from the SumUp app.
        "sumup_refund": sumup_refund_status,
    }


