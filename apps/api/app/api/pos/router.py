async def _verify_sumup_card_tenders(
    db: AsyncSession,
    request: CreateTransactionRequest,
) -> list:
    """Fail closed unless every card tender is PAID at SumUp for this sale.

    Browser-provided status and card metadata are deliberately ignored. The
    checkout is re-read from SumUp, matched to the authoritative attempt,
    amount and Vintiz idempotence key, then the trusted response overwrites the
    DTO fields that will be persisted on ``payments``.
    """
    from app.models.payment_attempt import PaymentAttempt, PaymentAttemptStatus
    from app.services.sumup_exchange_log import persist_sumup_exchanges
    from app.services.sumup_service import SumUpService

    card_tenders = [
        payment
        for payment in request.payments
        if payment.method in {"card", "carte"}
    ]
    if not card_tenders:
        return []
    if len(card_tenders) > 1:
        raise HTTPException(
            status_code=400,
            detail="Un seul règlement CB SumUp est autorisé par vente.",
        )

    service = SumUpService()
    if not service.is_configured or not service.merchant_code:
        raise HTTPException(status_code=503, detail="SumUp n'est pas configuré.")
    if settings.is_production and service.is_sandbox:
        raise HTTPException(
            status_code=503,
            detail="Une clé SumUp de test est interdite en production.",
        )

    verified: list[PaymentAttempt] = []
    for tender in card_tenders:
        if not tender.sumup_checkout_id:
            raise HTTPException(
                status_code=400,
                detail="Paiement CB sans identifiant de checkout SumUp.",
            )

        query = select(PaymentAttempt).where(
            PaymentAttempt.method == "card",
        )
        if tender.attempt_id:
            query = query.where(PaymentAttempt.id == tender.attempt_id)
        else:
            query = query.where(
                PaymentAttempt.sumup_checkout_id == tender.sumup_checkout_id
            )
        query = query.order_by(PaymentAttempt.created_at.desc()).with_for_update()
        attempt = (await db.execute(query)).scalars().first()
        if attempt is None:
            raise HTTPException(
                status_code=409,
                detail="Tentative CB SumUp introuvable ou non rattachée.",
            )
        if attempt.sumup_checkout_id != tender.sumup_checkout_id:
            raise HTTPException(status_code=409, detail="Checkout CB incohérent.")
        if request.client_uuid is None:
            raise HTTPException(
                status_code=400,
                detail="client_uuid obligatoire pour un encaissement CB.",
            )
        if attempt.foreign_transaction_id != str(request.client_uuid):
            raise HTTPException(
                status_code=409,
                detail="Ce checkout CB appartient à une autre intention de vente.",
            )

        expected = Decimal(str(tender.amount)).quantize(Decimal("0.01"))
        attempted = Decimal(str(attempt.amount)).quantize(Decimal("0.01"))
        if attempted != expected:
            raise HTTPException(
                status_code=409,
                detail="Le montant CB diffère de la tentative SumUp initiée.",
            )

        result = await service.get_checkout_status(tender.sumup_checkout_id)
        await persist_sumup_exchanges(db, service)
        if str(result.get("status", "")).upper() != "PAID":
            raise HTTPException(
                status_code=409,
                detail="Le paiement CB n'est pas confirmé PAID par SumUp.",
            )
        if result.get("amount") is None:
            raise HTTPException(
                status_code=409,
                detail="SumUp n'a pas retourné le montant payé; vente bloquée.",
            )
        paid_amount = Decimal(str(result["amount"])).quantize(Decimal("0.01"))
        if paid_amount != expected:
            raise HTTPException(
                status_code=409,
                detail=(
                    f"Montant SumUp incohérent: {paid_amount} € payé, "
                    f"{expected} € attendu."
                ),
            )

        # Replace every client-supplied SumUp field with the provider response.
        tender.sumup_transaction_id = result.get("sumup_transaction_id")
        tender.sumup_transaction_code = result.get("sumup_transaction_code")
        tender.sumup_auth_code = result.get("sumup_auth_code")
        tender.sumup_card_brand = result.get("sumup_card_brand")
        tender.sumup_card_last4 = result.get("sumup_card_last4")
        tender.sumup_environment = result.get("environment") or "production"

        attempt.status = PaymentAttemptStatus.succeeded
        attempt.sumup_transaction_id = tender.sumup_transaction_id
        attempt.sumup_transaction_code = tender.sumup_transaction_code
        attempt.sumup_auth_code = tender.sumup_auth_code
        attempt.sumup_card_brand = tender.sumup_card_brand
        attempt.sumup_card_last4 = tender.sumup_card_last4
        verified.append(attempt)

    return verified


@router.post("/transactions")
async def create_transaction(
    request: CreateTransactionRequest,
    db: AsyncSession = Depends(get_db),
    current_user: User = Depends(get_current_user),
):
    """Create a new sale transaction with payments."""
    # Idempotent replay must not call SumUp again or duplicate audit hooks.
    if request.client_uuid is not None:
        from app.models.pos import Transaction

        replay = (
            await db.execute(
                select(Transaction).where(
                    Transaction.client_uuid == request.client_uuid
                )
            )
        ).scalar_one_or_none()
        if replay is not None:
            return {
                "id": str(replay.id),
                "transaction_id": str(replay.id),
                "transaction_number": replay.transaction_number,
                "invoice_number": replay.invoice_number,
                "total_ttc": float(replay.total_ttc),
                "replayed": True,
            }

    pos_service = PosService(db)
    fiscal_service = FiscalService(db)

    verified_card_attempts = await _verify_sumup_card_tenders(db, request)

    # Plafond légal espèces (CMF art. L.112-6) — 1 000 € résident /
    # 15 000 € non-résident. Bloque par défaut, override manager possible
    # avec motif tracé en audit log.
    cash_check = validate_cash_payments(
        request.payments,
        is_tourist=request.customer_is_tourist,
    )
    if cash_check.over_cap:
        if not request.cash_override_reason:
            raise HTTPException(
                status_code=400,
                detail={
                    "code": "cash_cap_exceeded",
                    "cash_total_eur": float(cash_check.cash_total_eur),
                    "cap_eur": float(cash_check.cap_eur),
                    "is_tourist": cash_check.is_tourist,
                    "message": cash_check.reason,
                    "override_required": True,
                },
            )
        if current_user.role != UserRole.manager:
            raise HTTPException(
                status_code=403,
                detail={
                    "code": "cash_cap_override_manager_only",
                    "message": (
                        "Le dépassement du plafond espèces nécessite "
                        "l'autorisation d'un manager."
                    ),
                },
            )
        reason = request.cash_override_reason.strip()
        if len(reason) < 10:
            raise HTTPException(
                status_code=400,
                detail={
                    "code": "cash_override_reason_too_short",
                    "message": (
                        "Le motif d'override doit faire au moins "
                        "10 caractères et être circonstancié "
                        "(ex. n° passeport, nom client, justificatif)."
                    ),
                },
            )
        # Audit log immédiat — la transaction n'est pas encore créée,
        # donc entity_id reste NULL ; le hash chain de la transaction
        # tracera ensuite la liaison via timestamp + user_id.
        db.add(
            AuditLog(
                user_id=current_user.id,
                action="cash_cap_override",
                entity="transaction",
                entity_id=None,
                data={
                    "cash_total_eur": float(cash_check.cash_total_eur),
                    "cap_eur": float(cash_check.cap_eur),
                    "is_tourist": cash_check.is_tourist,
                    "reason": reason,
                    "client_uuid": (
                        str(request.client_uuid)
                        if request.client_uuid
                        else None
                    ),
                },
            )
        )
        logger.warning(
            "cash_cap_override by user=%s total=%.2f€ cap=%.2f€ is_tourist=%s",
            current_user.id,
            cash_check.cash_total_eur,
            cash_check.cap_eur,
            cash_check.is_tourist,
        )

    cashier_id = request.cashier_id or current_user.id
    if request.cashier_id is not None:
        cashier = (
            await db.execute(
                select(User).where(
                    User.id == request.cashier_id,
                    User.is_active.is_(True),
                )
            )
        ).scalar_one_or_none()
        if cashier is None:
            raise HTTPException(
                status_code=400,
                detail="Caissier inconnu ou désactivé.",
            )

    transaction = await pos_service.create_transaction(
        user_id=current_user.id,
        items=request.items,
        payments=request.payments,
        client_id=request.client_id,
        # NF525 traceability: even when the POS did not perform a separate
        # cashier-PIN identification, attribute the sale to the authenticated
        # operator instead of leaving a new fiscal transaction anonymous.
        cashier_id=cashier_id,
        client_uuid=request.client_uuid,
        is_invoice=request.is_invoice,
        client_siret=request.client_siret,
        client_company_name=request.client_company_name,
        client_billing_address=request.client_billing_address,
        template_id=request.template_id,
        coupon_code=request.coupon_code,
    )

    # If create_transaction returned the existing row (idempotent replay
    # via client_uuid), the hash chain is already set and the analytics
    # events were emitted on the first call. Skip both.
    is_replay = (
        request.client_uuid is not None
        and transaction.hash_chain
    )
    if is_replay:
        return {
            "id": str(transaction.id),
            "transaction_id": str(transaction.id),
            "transaction_number": transaction.transaction_number,
            "total_ttc": float(transaction.total_ttc),
            "replayed": True,
        }

    # V2 — gift flag from the POS micro-question. A gift counts for CA +
    # loyalty but is excluded from the taste profile (the nightly recompute
    # then drops it from the centroid).
    if request.is_gift:
        transaction.is_gift = True
        transaction.exclude_from_taste = True

    for attempt in verified_card_attempts:
        attempt.transaction_id = transaction.id

    # Generate fiscal hash chain
    await fiscal_service.sign_transaction(transaction)

    # Coupon redemption + analytics events
    await pos_service.finalize_sale(
        transaction,
        user_id=current_user.id,
    )

    return {
        "id": str(transaction.id),
        "transaction_id": str(transaction.id),
        "transaction_number": transaction.transaction_number,
        "total_ttc": float(transaction.total_ttc),
    }


